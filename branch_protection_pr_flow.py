    print("🎯 Failed Quality Gates:")
    print(f"   - Alle grün: {'✅ YES' if failed_all_green else '❌ NO'}")
    
    if not failed_all_green:
        failed_pr_result = failed_pr_flow.create_draft_pr(
            title="Failed Feature Implementation",
            description="This feature implementation failed quality gates."
        )
        
        print("📝 Failed PR-Versuch:")
        print(f"   - Erstellt: {'✅ SUCCESS' if failed_pr_result.success else '❌ FAILED (erwartet)'}")
        print(f"   - Fehler: {failed_pr_result.error_message}")
    
    # Test 3: Status-Report
    print("\n📊 Test 3: Status-Report")
    
    status_report = pr_flow.generate_status_report()
    
    print("📋 Status-Report:")
    print(f"   - Spec ID: {status_report['spec_id']}")
    print(f"   - Branch Protection: {status_report['branch_protection']['verified']}")
    print(f"   - Quality Gates: {status_report['summary']['passed_gates']}/{status_report['summary']['total_gates']}")
    print(f"   - Artifacts: {status_report['artifacts']['count']}")
    print(f"   - Ready for PR: {status_report['summary']['ready_for_pr']}")
    
    # Speichere Status-Report
    report_file = "branch_protection_status_report.json"
    with open(report_file, 'w', encoding='utf-8') as f:
        json.dump(status_report, f, indent=2, ensure_ascii=False)
    
    print(f"💾 Status-Report gespeichert: {report_file}")
    
    # Test 4: PR-Content-Vorschau
    print("\n📄 Test 4: PR-Content-Vorschau")
    
    pr_content = pr_flow.generate_pr_content(
        title="Automated Feature Implementation",
        description="Complete feature implementation with all quality gates.",
        changes_summary="Added new functionality, tests, and documentation."
    )
    
    print(f"📝 PR-Titel: {pr_content['title']}")
    print(f"📄 PR-Beschreibung ({len(pr_content['description'])} Zeichen):")
    print(pr_content['description'][:400] + "..." if len(pr_content['description']) > 400 else pr_content['description'])
    
    print("\n✅ Branch Protection & PR Flow Demo abgeschlossen!")
    print("🔀 Vollständiger PR-Workflow mit Branch-Protection und Artefakt-Integration")
    
